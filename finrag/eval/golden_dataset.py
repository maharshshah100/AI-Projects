"""
golden_dataset.py — Hand-labeled evaluation set for the FinRAG pipeline.

Every example below was labeled by directly reading the actual chunk content
(see the inspection commands in this session) -- not generated by an LLM and
not guessed. This matters: a golden dataset generated by the same kind of
model you're evaluating grades the system against its own blind spots, not
against ground truth. Each example specifies:

  - query: the question to ask
  - company_filter: expected ticker(s) the decomposer should route to
  - expected_chunk_ids: the chunk_id(s) that actually contain the answer
    (used for recall@k / MRR -- retrieval-quality metrics)
  - expected_facts: specific strings that MUST appear in a faithful answer
    (used for faithfulness scoring -- generation-quality metric)
  - should_answer: False for examples that should be declined, not answered
  - category: lookup / comparison / superlative / out_of_scope / nuance
"""
from dataclasses import dataclass, field
from typing import List, Optional


@dataclass
class GoldenExample:
    query: str
    company_filter: Optional[List[str]]
    expected_chunk_ids: List[str]
    expected_facts: List[str] = field(default_factory=list)
    should_answer: bool = True
    category: str = "lookup"


